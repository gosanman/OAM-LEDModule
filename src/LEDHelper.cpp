// re-calculates & fills gamma table
void LEDHelper::calcGammaTable(float gamma, uint8_t *table)
{
    for (size_t i = 0; i < 256; i++)
    {
        table[i] = (int)(powf((float)i / 255.0f, gamma) * 255.0f + 0.5f);
    }
}

